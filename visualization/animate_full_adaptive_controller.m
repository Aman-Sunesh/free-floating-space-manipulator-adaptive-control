x_d_base(k,:) = x_d.';
delta_x_base(k,:) = (x - x_d).';


[Hb, Hbm, ~] = momentum_matrices( ...
    phi, ...
    cfg.l, ...
    cfg.r, ...
    cfg.m, ...
    cfg.I);

omega_base(k) = omega_base(k-1);
reaction_base(k) = reaction_base(k-1);


