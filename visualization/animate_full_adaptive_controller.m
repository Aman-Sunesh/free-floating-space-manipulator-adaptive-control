%% =========================================================
% FULL ADAPTIVE CONTROLLER
%
% This is the actual controller implementation used for
% reproducing the Xu et al. simulation.
%
% It includes:
%
%   - spacecraft attitude regulation
%   - end-effector task-space tracking
%   - nonzero initial angular momentum compensation
%   - nonzero translational momentum compensation
%   - dynamic parameter adaptation
%   - kinematic parameter adaptation
%% =========================================================

fprintf('Running full adaptive controller...\n');

sim_full = simulate_plant(cfg);


% Physical constants shared by BOTH cases
p0_true = sim_full.p0_true;

% In the reduced kinematic model this is the constant
% translational/system-COM velocity term.
vC_true = sim_full.v0_true;


% Initial total system COM
[~, ~, ~, ~, rC_system_0] = com_positions( ...
    cfg.qm_0, ...
    cfg.qb_0, ...
    cfg.R_C0_0, ...
    cfg.l, ...
    cfg.r, ...
    cfg.m);


%% =========================================================
% TASK-SPACE-ONLY BASELINE
%
% This is intentionally NOT the Xu adaptive controller.
%
% It tries to make the EE follow the same desired trajectory,
% but assumes the joints can simply perform inverse-kinematic
% task-space motion.
%
% It does NOT compensate for:
%
%   - spacecraft attitude reaction
%   - p0
%   - v0
%   - dynamic uncertainty
%   - kinematic uncertainty
%
% The ACTUAL free-floating spacecraft is still governed by
% angular-momentum conservation.
%% =========================================================

fprintf('Running task-space-only baseline...\n');


dt = cfg.dt;

t = sim_full.t;
N = length(t);


% Moderate baseline task-space gain.
%
% This is only for the visual proof-of-concept; it is not a
% parameter from the paper.
K_task_demo = 3.0 * eye(2);


% Storage
theta_base = zeros(N,1);
phi_base = zeros(N,3);

omega_base = zeros(N,1);

x_base = zeros(N,2);
x_d_base = zeros(N,2);
delta_x_base = zeros(N,2);

reaction_base = zeros(N,1);

rC0_base = zeros(N,2);


% Initial configuration
theta_base(1) = cfg.qb_0;
phi_base(1,:) = cfg.qm_0.';


% Simulate task-space-only baseline
for k = 1:N-1

    tk = t(k);

    theta_b = theta_base(k);
    phi = phi_base(k,:).';


    %% -----------------------------------------------------
    % Total system COM motion
    %
    % No external forces:
    %
    % rC(t) = rC(0) + vC*t
    %% -----------------------------------------------------

    rC_system = ...
        rC_system_0 ...
        + vC_true * tk;


    % Recover spacecraft COM from total system COM
    r_C0 = spacecraft_com_from_system_com( ...
        rC_system, ...
        theta_b, ...
        phi, ...
        cfg);

    rC0_base(k,:) = r_C0.';


    % Current physical end-effector position
    joints = joint_positions( ...
        r_C0, ...
        theta_b, ...
        phi, ...
        cfg.L, ...
        cfg.r(1));

    x = joints(:,end);


    % Same desired task-space trajectory as the paper
    [x_d, x_d_dot] = desired_trajectory(tk);


    x_base(k,:) = x.';
    x_d_base(k,:) = x_d.';

    delta_x = x - x_d;

    delta_x_base(k,:) = delta_x.';


    %% -----------------------------------------------------
    % Baseline task-space controller
    %
    % Uses the manipulator geometric Jacobian as if joint
    % motion alone were responsible for task-space motion.
    %
    % It deliberately ignores spacecraft reaction.
    %% -----------------------------------------------------

    [~, Jm_geom] = jacobians( ...
        phi, ...
        cfg.L, ...
        theta_b, ...
        cfg.r(1));


    desired_task_velocity = ...
        x_d_dot ...
        - K_task_demo * delta_x;


    phi_dot = ...
        pinv(Jm_geom) ...
        * desired_task_velocity;


    %% -----------------------------------------------------
    % TRUE free-floating spacecraft response
    %
    % p0 = Hb*omega_b + Hbm*phi_dot
    %% -----------------------------------------------------
   
    [Hb, Hbm, ~] = momentum_matrices( ...
        phi, ...
        cfg.l, ...
        cfg.r, ...
        cfg.m, ...
        cfg.I);
    
    omega_b = ...
        (p0_true - Hbm*phi_dot) / Hb;


    reaction = ...
        Hbm * phi_dot;


    omega_base(k) = omega_b;
    reaction_base(k) = reaction;


    % Integrate configuration
    theta_base(k+1) = ...
        theta_b ...
        + dt * omega_b;


    phi_base(k+1,:) = ...
        (phi + dt*phi_dot).';

end


% Final baseline point
k = N;

theta_b = theta_base(k);
phi = phi_base(k,:).';

rC_system = ...
    rC_system_0 ...
    + vC_true * t(k);

r_C0 = spacecraft_com_from_system_com( ...
    rC_system, ...
    theta_b, ...
    phi, ...
    cfg);

