%% =========================================================
% Local helper:
% recover spacecraft COM from total system COM
%% =========================================================

function r_C0 = spacecraft_com_from_system_com( ...
    rC_system, theta_b, phi, cfg)

    % Compute where the total system COM would lie if the
    % spacecraft COM were placed at the origin.
    [~, ~, ~, ~, rC_relative] = com_positions( ...
        phi, ...
        theta_b, ...
        [0;0], ...
        cfg.l, ...
        cfg.r, ...
        cfg.m);


    % Since all COM locations translate by the same r_C0:
    %
    % rC_system = r_C0 + rC_relative

    r_C0 = ...
        rC_system ...
        - rC_relative;

end


%% =========================================================
% Local visualization helper
%
% joints(:,1) = J1
% joints(:,2) = J2
% joints(:,3) = J3
% joints(:,4) = end effector
%% =========================================================

function joints = joint_positions( ...
    r_C0, theta_b, phi, L, r0)

    Rb = [
        cos(theta_b), -sin(theta_b);
        sin(theta_b),  cos(theta_b)
    ];


    J1 = ...
        r_C0 ...
        + Rb * [r0;0];


    a1 = ...
        theta_b ...
        + phi(1);

    a2 = ...
        theta_b ...
        + phi(1) ...
        + phi(2);

    a3 = ...
        theta_b ...
        + phi(1) ...
        + phi(2) ...
        + phi(3);


    J2 = ...
        J1 ...
        + L(1) * ...
          [cos(a1);sin(a1)];


    J3 = ...
        J2 ...
        + L(2) * ...
          [cos(a2);sin(a2)];


    EE = ...
        J3 ...
        + L(3) * ...
          [cos(a3);sin(a3)];


    joints = [
        J1, ...
        J2, ...
        J3, ...
        EE
    ];

end