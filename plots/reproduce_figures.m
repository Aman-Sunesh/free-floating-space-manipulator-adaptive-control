clear;
clc;
close all;

%% Add project folders
project_root = fileparts(fileparts(mfilename('fullpath')));
addpath(genpath(project_root));

cfg = paper_params();

%% =========================================================
% Run nonzero-momenta adaptive controller
%% =========================================================

fprintf('Running nonzero-momenta adaptive controller...\n');

sim_nonzero = simulate_plant(cfg);


%% =========================================================
% Run zero-momenta adaptive controller
%
% Needed only for Figs. 2-4.
%% =========================================================

have_zero = exist('simulate_zero_momentum_plant', 'file') == 2;

if have_zero
    fprintf('Running zero-momenta adaptive controller...\n');

    sim_zero = simulate_zero_momentum_plant(cfg);
else
    warning([ ...
        'simulate_zero_momentum_plant.m does not exist yet. ', ...
        'Figs. 2-4 will show only the nonzero-momenta result.' ...
        ]);
end


%% =========================================================
% Output directory
%% =========================================================

output_dir = fullfile(project_root, 'results', 'figures');

if ~exist(output_dir, 'dir')
    mkdir(output_dir);
end


%% =========================================================
% Common settings
%% =========================================================

t = sim_nonzero.t;

lw = 1.2;

blue = [0.0, 0.25, 0.80];
red  = [1.0, 0.0, 0.0];


%% =========================================================
% FIGURE 2
% Spacecraft angular velocity
%% =========================================================

figure('Name', 'Fig. 2 - Spacecraft Angular Velocity', ...
       'Color', 'w');

hold on;
box on;

set(gca, ...
    'Color', 'w', ...
    'XColor', 'k', ...
    'YColor', 'k');

if have_zero
    plot( ...
        sim_zero.t, ...
        rad2deg(sim_zero.omega_b), ...
        '--', ...
        'Color', blue, ...
        'LineWidth', lw);
end

plot( ...
    t, ...
    rad2deg(sim_nonzero.omega_b), ...
    '-', ...
    'Color', red, ...
    'LineWidth', lw);

xlim([0 8]);
ylim([-3.5 1]);

xticks(0:1:8);
yticks(-3.5:0.5:1);

xlabel('Time (s)');
ylabel('Spacecraft angular velocity (degree \cdot s^{-1})');

if have_zero
    lgd = legend( ...
        'zero-momenta adaptive controller', ...
        'nonzero-momenta adaptive controller', ...
        'Location', 'northeast');
else
    lgd = legend( ...
        'nonzero-momenta adaptive controller', ...
        'Location', 'northeast');
end

set(lgd, ...
    'Color', 'w', ...
    'TextColor', 'k');

set(gca, 'FontSize', 11);

exportgraphics( ...
    gcf, ...
    fullfile(output_dir, 'Fig2_spacecraft_angular_velocity.png'), ...
    'Resolution', 300, ...
    'BackgroundColor', 'white');


