function [Yd_bar, Yd] = dynamic_regressor(phi, omega_b, phi_dot)

    % Joint angles
    q1 = phi(1);
    q2 = phi(2);
    q3 = phi(3);

    % Joint velocities
    q1_dot = phi_dot(1);
    q2_dot = phi_dot(2);
    q3_dot = phi_dot(3);
    
    % Dynamic regressor
    Yd = [
        cos(q1) * ...
            (2*omega_b + q1_dot), ...
        cos(q2) * ...
            (2*omega_b + 2*q1_dot + q2_dot), ...
        cos(q2 + q3) * ...
            (2*omega_b + 2*q1_dot + q2_dot + q3_dot), ...
        cos(q3) * ...
            (2*omega_b + 2*q1_dot + 2*q2_dot + q3_dot), ...
        cos(q1 + q2) * ...
            (2*omega_b + q1_dot + q2_dot), ...
        cos(q1 + q2 + q3) * ...
            (2*omega_b + q1_dot + q2_dot + q3_dot), ...
        omega_b, ...
        q1_dot, ...
        q2_dot, ...
        q3_dot
    ];

    % Generalized regressor including unknown initial angular momentum:
    %
    % Yd_bar * [a_d; p0] = Yd*a_d - p0
    Yd_bar = [Yd, -1];

end